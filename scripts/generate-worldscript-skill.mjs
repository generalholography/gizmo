function stripNoPromptRegions(source) {
  return source
    .replace(/^[ \t]*\/\/[ \t]*#region noprompt[\s\S]*?^[ \t]*\/\/[ \t]*#endregion[ \t]*$/gm, '')
    .replace(/^[ \t]*\/\/[ \t]*#region noprompt[\s\S]*?^[ \t]*\/\/[ \t]*#endregion[ \t]*$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function extractFunctionBody(source, functionName) {
  const marker = `function ${functionName}`;
  const start = source.indexOf(marker);
  if (start === -1) throw new Error(`Could not find ${functionName}`);
  const firstBrace = source.indexOf('{', start);
  let depth = 0;
  for (let index = firstBrace; index < source.length; index += 1) {
    const char = source[index];
    if (char === '{') depth += 1;
    if (char === '}') {
      depth -= 1;
      if (depth === 0) return source.slice(firstBrace + 1, index);
    }
  }
  throw new Error(`Could not parse ${functionName}`);
}

function extractApiMethods(worldScriptSource) {
  const body = extractFunctionBody(worldScriptSource, 'buildWorldScriptApi');
  const methodPattern = /^\s*([A-Za-z0-9_]+):\s*(?:\(([^)]*)\)|([^=,]+)=>|([^=,]+)\s*=>)/gm;
  const methods = [];
  let match;
  while ((match = methodPattern.exec(body)) !== null) {
    const name = match[1];
    if (name === 'ecsWorld') continue;
    const params = (match[2] ?? match[3] ?? match[4] ?? '').trim();
    methods.push({ name, params: params.replace(/\s+/g, ' ') });
  }
  return methods;
}

function jsonForTs(value) {
  return JSON.stringify(value).replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
}

const validBoxHelper = `function boxPart(lengthX, lengthY, lengthZ, color) {
  return {
    geometry: { type: 'box', params: { lengthX, lengthY, lengthZ } },
    material: { type: 'solid', params: { color, roughness: 0.8 } }
  };
}

function boxEntity(name, x, y, z, lengthX, lengthY, lengthZ, color = '#7b8794') {
  return {
    Info: { name },
    Transform: { x, y, z },
    Body: { type: 'composite', params: { parts: [boxPart(lengthX, lengthY, lengthZ, color)] } },
    MotionSource: { type: 'static', params: {} }
  };
}`;

